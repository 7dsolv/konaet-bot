function registration_url = abrir_cadastro_konaet(open_browser)
%ABRIR_CADASTRO_KONAET Abre o cadastro oficial preconfigurado da GitHub App.
%   abrir_cadastro_konaet(false) devolve a URL sem abrir o navegador.
%   O cadastro e a instalacao sao concluidos na sessao do proprietario GitHub.

if nargin < 1
    open_browser = true;
end
validateattributes(open_browser, {'logical'}, {'scalar'});
root = fileparts(mfilename('fullpath'));
config = jsondecode(fileread(fullfile(root, 'github-app.json')));
assert(config.public && ~config.hook_attributes.active, ...
    'A configuracao deve ser publica e sem servidor webhook.');
permissions = config.default_permissions;
assert(strcmp(permissions.contents, 'write') && ...
    strcmp(permissions.pull_requests, 'write'), ...
    'Permissoes diferentes do contrato de commits e propostas.');
uri = matlab.net.URI('https://github.com/settings/apps/new');
uri.Query = matlab.net.QueryParameter( ...
    'name', config.name, ...
    'description', config.description, ...
    'url', config.url, ...
    'public', 'true', ...
    'webhook_active', 'false', ...
    'contents', permissions.contents, ...
    'pull_requests', permissions.pull_requests);
registration_url = char(uri);
if open_browser
    web(registration_url, '-browser');
end
end
