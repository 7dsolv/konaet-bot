function plan = konaet_activation_policy(app, installations)
%KONAET_ACTIVATION_POLICY Autoriza somente a App e a conta do projeto.
assert(isstruct(app) && isfield(app,'slug') && strcmp(app.slug,'konaet') && ...
    isfield(app,'id') && app.id == 5602778, ...
    'Konaet:WrongApp', 'A chave nao pertence ao cadastro KONAET esperado.');
assert(isfield(app,'owner') && strcmp(app.owner.login,'7dsolv'), ...
    'Konaet:WrongOwner', 'A App precisa pertencer a 7dsolv.');
assert(isfield(app,'client_id') && ~isempty(regexp(app.client_id, ...
    '^[A-Za-z0-9_-]+$','once')), 'Konaet:InvalidClientId', 'Client ID ausente ou invalido.');
assert(iscell(installations) && numel(installations) == 2, ...
    'Konaet:MissingInstallation', 'Verifique a instalacao nos dois repositorios.');
ids = zeros(1,2);
for k = 1:2
    item = installations{k};
    assert(isstruct(item) && isfield(item,'id') && isnumeric(item.id) && ...
        isscalar(item.id) && isfinite(item.id) && item.id > 0 && item.id == fix(item.id) && ...
        isfield(item,'app_id') && item.app_id == app.id && ...
        isfield(item,'account') && strcmp(item.account.login,'7dsolv'), ...
        'Konaet:WrongInstallation', 'Instalacao nao corresponde a App e conta esperadas.');
    assert(isfield(item,'permissions') && isfield(item.permissions,'contents') && ...
        strcmp(item.permissions.contents,'write') && ...
        isfield(item.permissions,'pull_requests') && strcmp(item.permissions.pull_requests,'write'), ...
        'Konaet:MissingPermission', 'A instalacao precisa de contents e pull_requests em write.');
    assert(~isfield(item,'suspended_at') || isempty(item.suspended_at), ...
        'Konaet:SuspendedInstallation', 'A instalacao esta suspensa.');
    ids(k) = item.id;
end
assert(ids(1) == ids(2), 'Konaet:WrongInstallation', 'As instalacoes devem ser da mesma conta.');
plan = struct('owner','7dsolv','app_slug','konaet','app_id',app.id, ...
    'client_id',app.client_id,'installation_id',ids(1), ...
    'repositories',{{'7dsolv/konaet-bot','7dsolv/RealidadeQuantica'}});
end
